#!/usr/bin/env python3
"""Generate docs/configuration.md from the pydantic models in job_apply_mcp.config (ADR-0020).

    python scripts/gen_config_docs.py            # rewrite docs/configuration.md
    python scripts/gen_config_docs.py --check    # exit 1 if the file is stale (used by tests/CI)

Descriptions come from the inline `# comments` next to each field in config.py, so documenting a knob there
documents it here. Output is platform-independent (POSIX default paths are rendered).
"""
from __future__ import annotations

import argparse
import inspect
import json
import os
import re
import sys
import types
import typing
from pathlib import Path

from pydantic import BaseModel
from pydantic_core import to_jsonable_python

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "configuration.md"


def _neutral_env() -> None:
    """Render POSIX default paths regardless of the machine running the generator."""
    sys.path.insert(0, str(ROOT / "src"))
    for k in ("XDG_CONFIG_HOME", "XDG_DATA_HOME"):
        os.environ.pop(k, None)
    from job_apply_mcp import paths

    paths.sys = types.SimpleNamespace(platform="linux")  # type: ignore[assignment]


def _comments(model: type[BaseModel]) -> dict[str, str]:
    out: dict[str, str] = {}
    for line in inspect.getsource(model).splitlines():
        m = re.match(r"\s{4}(\w+)\s*:\s*.*?#\s*(.+?)\s*$", line)
        if m and not line.strip().startswith("#"):
            out[m.group(1)] = m.group(2)
    return out


def _type_name(t: object) -> str:
    return re.sub(r"\bjob_apply_mcp\.config\.", "", str(t).replace("typing.", "")).replace("<class '", "").replace("'>", "")


def _default(v: object) -> str:
    if type(v).__name__ == "PydanticUndefinedType":
        return "required"
    if isinstance(v, BaseModel):
        return "(see section)"
    s = json.dumps(to_jsonable_python(v), default=str, ensure_ascii=False)
    s = s if s != "null" else "none"
    return s if len(s) <= 90 else s[:87] + "..."


def _submodel(annotation: object) -> type[BaseModel] | None:
    if inspect.isclass(annotation) and issubclass(annotation, BaseModel):
        return annotation
    return None


def _dict_value_model(annotation: object) -> type[BaseModel] | None:
    """dict[str, Model] and dict[str, list[Model]] get their own section (keys are user-chosen names)."""
    args = typing.get_args(annotation)
    if typing.get_origin(annotation) is dict and len(args) == 2:
        inner = typing.get_args(args[1])[0] if typing.get_origin(args[1]) is list else args[1]
        return _submodel(inner)
    return None


def render() -> str:
    _neutral_env()
    from job_apply_mcp.config import Settings

    lines = [
        "# Configuration reference", "",
        "<!-- Generated by scripts/gen_config_docs.py from src/job_apply_mcp/config.py. Do not edit by hand. -->", "",
        ("Settings load in this order, later wins: built-in defaults, the user file "
        "(`~/.config/job-apply-mcp/config.toml`, `%APPDATA%\\job-apply-mcp\\config.toml` on Windows, or "
        "`$JOB_APPLY_MCP_CONFIG`), `./job-apply-mcp.toml`, then environment variables "
        "`JOB_APPLY__SECTION__KEY=value` (double underscore nests, e.g. `JOB_APPLY__LLM__ALLOW_CLOUD=false`). "
        "Secrets (API keys, IMAP passwords) are only ever read from the environment."), "",
        ("**Trust model (ADR-0021):** security-relaxing values (`apply.approval_mode`, `apply.auto_approve`, "
        "`dry_run=false`, `control.apply_enabled=true`, `control.dev_mode=false`) are honored only from the "
        "platform-default user config, owned by you and not group/world-writable. A file selected via "
        "`JOB_APPLY_MCP_CONFIG`, the project file and `JOB_APPLY__*` env can only make them stricter."), "",
        ("**Submission caps (ADR-0035):** `apply.daily_limit` (25), `apply.daily_limit_per_platform` (10) and "
        "`apply.run_limit` (10) cap LIVE submits (dry runs never count). **`0` means no limit and removes that safety "
        "cap.** The legacy `control.params.quota.per_day` / `per_platform_per_day` / `per_run` keys still work, win "
        "when set, and also take `0` for off. Lowering a cap is accepted from any source; raising it above the default "
        "or setting `0` is honored only from the trusted user config (same rule as the trust model above). "
        "`control_status` (MCP) and `job-apply-mcp doctor` show limits, used in the last 24h and remaining."), "",
        "Run `job-apply-mcp init` to create a starter file and `job-apply-mcp doctor` to validate it.", ""]
    seen: list[tuple[str, type[BaseModel]]] = [("", Settings)]
    queue = list(seen)
    while queue:
        prefix, model = queue.pop(0)
        com = _comments(model)
        title = f"`[{prefix}]`" if prefix else "Top level"
        rows = []
        for name, f in model.model_fields.items():
            sub = _submodel(f.annotation)
            dsub = _dict_value_model(f.annotation)
            if dsub is not None:
                child = (f"{prefix}.{name}.<name>" if prefix else f"{name}.<name>", dsub)
                seen.append(child)
                queue.append(child)
            if sub is not None:
                child = (f"{prefix}.{name}" if prefix else name, sub)
                seen.append(child)
                queue.append(child)
                continue
            cells = [f"`{name}`", f"`{_type_name(f.annotation)}`",
                     f"`{_default(f.get_default(call_default_factory=True))}`" if not f.is_required() else "`required`", com.get(name, "")]
            rows.append("| " + " | ".join(c.replace("|", "\\|") for c in cells) + " |")
        doc = inspect.cleandoc(model.__doc__ or "")
        lines += [f"## {title}", ""]
        if prefix and doc:
            lines += [doc.split("\n\n")[0].replace("\n", " "), ""]
        if rows:
            lines += ["| Key | Type | Default | Notes |", "|---|---|---|---|", *[r.replace("\n", " ") for r in rows], ""]
    lines += ["## Profile `[preferences]` (profile.toml)", "",
              "Yes/no facts in your profile, not in config.toml. Unset (`None`) leaves the matching question unresolved.", "",
              "| Key | Type | Default | Notes |", "|---|---|---|---|",
              "| `willing_to_relocate` | `bool \\| None` | `none` |  |",
              "| `needs_relocation_support` | `bool \\| None` | `none` |  |",
              "| `open_to_hybrid` | `bool \\| None` | `none` |  |",
              "| `open_to_onsite` | `bool \\| None` | `none` |  |",
              ("| `acknowledge_privacy_notices` | `bool \\| None` | `none` | `true` lets the mapper tick/choose the "
               "acknowledgement on applicant privacy notices only (ADR-0034). Never attestations (`policy.stop_phrases`), "
               "truthfulness, AI-use, background/drug-check, arbitration, terms-of-employment or marketing/talent-community "
               "opt-ins. `none`/`false`: such questions stay unresolved. |"), ""]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print("docs/configuration.md is stale: run python scripts/gen_config_docs.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
