"""ImproveService: request_feature (proposal -> coder -> tested PR) and the RSI report/apply loop."""
from __future__ import annotations

import fnmatch
import json
import re
import time
from pathlib import Path
from typing import Any

from ..config import Settings
from . import analyze as an
from . import coder as coders
from . import context as ctxmod
from . import proposal as prop
from .classify import classify
from .playbook import PlaybookStore, redact, scrub
from .runner import CommandRunner, SubprocessRunner

SECRET_RX = re.compile(r"(sk-[A-Za-z0-9]{20,}|AKIA[0-9A-Z]{16}|-----BEGIN [A-Z ]*PRIVATE KEY|"
                       r"(?i:api[_-]?key|secret|token|password)\s*[=:]\s*['\"][^'\"\s]{12,}['\"])")
PR_FOOTER = "Generated by job-apply-mcp self-improvement; requires human review"


def path_ok(path: str, allowed: list[str], forbidden: list[str]) -> bool:
    if any(fnmatch.fnmatch(path, f) or fnmatch.fnmatch(Path(path).name, f) or path.startswith(f)
           or f"/{f.strip('/')}/" in f"/{path}" for f in forbidden):
        return False
    return any(path.startswith(a) for a in allowed)


class ImproveService:
    def __init__(self, settings: Settings, runner: CommandRunner | None = None, repo: Path | None = None):
        self.s = settings
        self.cfg = settings.improve
        self.runner = runner or SubprocessRunner()
        self.data = Path(settings.paths.data_dir).expanduser()
        self.root = self.data / "improve"
        self.repo = Path(self.cfg.repo_path).expanduser() if self.cfg.repo_path else (
            repo or Path(__file__).resolve().parents[3])
        self.playbooks = PlaybookStore(self.data / "playbooks")

    # ---- (1) request_feature -------------------------------------------------------------------
    async def request_feature(self, description: str, kind: str | None = None) -> dict[str, Any]:
        k = classify(description, kind)
        props = an.analyze(an.read_events(self.data, self.cfg.window_days), min_count=self.cfg.min_cluster_count)
        pack = ctxmod.build_pack(self.repo, k, description, props, self.cfg.context_max_chars)
        p = prop.build(description, k, pack)
        pdir = prop.save(p, self.data / "proposals")
        out: dict[str, Any] = {"id": p.id, "kind": k, "risk": p.risk, "proposal": str(pdir / "proposal.md"),
                               "coder": self.cfg.coder}
        name = self.cfg.coder
        if name not in coders.BACKENDS:
            raise ValueError(f"unknown coder '{name}'; known: {sorted(coders.BACKENDS)}")
        if name == "none":
            return self._finish(pdir, out, "proposal_only")
        if name == "client":
            out["client_task"] = {"type": "implement_proposal", "proposal": str(pdir / "proposal.md"),
                                  "branch": self._branch(p), "base": f"{self.cfg.remote}/{self.cfg.base_branch}",
                                  "prompt": coders.build_prompt(p, self.cfg),
                                  "rules": "tests must pass; never merge or push to base; PR body must end with: "
                                           + PR_FOOTER}
            return self._finish(pdir, out, "client_task")
        return self._finish(pdir, out | await self._implement(p, pdir), None)

    def _branch(self, p: prop.FeatureProposal) -> str:
        return f"{self.cfg.branch_prefix}{p.branch_suffix}"

    def _finish(self, pdir: Path, out: dict, status: str | None) -> dict:
        if status:
            out["status"] = status
        (pdir / "status.json").write_text(json.dumps(out, indent=1))
        return out

    async def _git(self, args: list[str], cwd: Path, timeout: float = 120):
        return await self.runner.run(["git", *args], cwd=str(cwd), timeout=timeout)

    async def _implement(self, p: prop.FeatureProposal, pdir: Path) -> dict[str, Any]:
        cfg, branch = self.cfg, self._branch(p)
        base = f"{cfg.remote}/{cfg.base_branch}"
        # Hard rails: the branch must be an auto branch and never the base.
        if not branch.startswith(cfg.branch_prefix) or branch.split("/")[-1] == cfg.base_branch or not cfg.branch_prefix:
            return {"status": "refused", "detail": "branch prefix misconfigured"}
        wt = Path(cfg.worktree_dir).expanduser() / p.id if cfg.worktree_dir else self.root / "worktrees" / p.id
        wt.parent.mkdir(parents=True, exist_ok=True)
        await self._git(["fetch", "-q", cfg.remote, cfg.base_branch], self.repo)
        r = await self._git(["worktree", "add", "-b", branch, str(wt), base], self.repo)
        if not r.ok:
            return {"status": "worktree_failed", "detail": r.err[-300:]}
        res: dict[str, Any] = {"branch": branch}
        call = coders.BACKENDS[cfg.coder](p, cfg, self.s)
        c = await self.runner.run(call.argv, cwd=str(wt), timeout=cfg.coder_timeout_s, env=call.env)
        (pdir / "coder.log").write_text((c.out + "\n" + c.err)[-8000:])
        if not c.ok:
            return res | {"status": "coder_failed", "detail": c.err[-300:], "worktree": str(wt)}
        await self._git(["add", "-A"], wt)
        names = (await self._git(["diff", "--cached", "--name-only"], wt)).out.split()
        if not names:
            return res | {"status": "no_changes", "worktree": str(wt)}
        bad = [n for n in names if not path_ok(n, cfg.allowed_paths, cfg.forbidden_paths)]
        if bad:
            return res | {"status": "path_violation", "paths": bad[:5], "worktree": str(wt)}
        diff = (await self._git(["diff", "--cached"], wt)).out
        if any(SECRET_RX.search(ln[1:]) for ln in diff.splitlines() if ln.startswith("+") and not ln.startswith("+++")):
            return res | {"status": "secret_detected", "worktree": str(wt)}
        for cmd in cfg.test_commands:
            t = await self.runner.run(cmd, cwd=str(wt), timeout=cfg.coder_timeout_s)
            if not t.ok:
                (pdir / "tests.log").write_text((t.out + t.err)[-8000:])
                return res | {"status": "tests_failed", "cmd": " ".join(cmd), "worktree": str(wt)}
        msg = f"{p.kind}: {p.description.strip()[:60]}\n\n{PR_FOOTER}.\n\nCo-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>"
        cm = await self._git(["commit", "-q", "-m", msg], wt)
        if not cm.ok:
            return res | {"status": "commit_failed", "detail": cm.err[-300:], "worktree": str(wt)}
        if not cfg.open_pr:
            return res | {"status": "committed_local", "worktree": str(wt)}
        pu = await self._git(["push", "-u", cfg.remote, f"{branch}:{branch}"], wt)
        if not pu.ok:
            return res | {"status": "push_failed", "detail": pu.err[-300:], "worktree": str(wt)}
        body = redact(prop.to_markdown(p) + f"\n---\n{PR_FOOTER}.\n")
        bf = pdir / "pr_body.md"
        bf.write_text(body)
        argv = ["gh", "pr", "create", "--base", cfg.base_branch, "--head", branch,
                "--title", f"[auto] {p.description.strip()[:70]}", "--body-file", str(bf)]
        if cfg.gh_repo:
            argv += ["--repo", cfg.gh_repo]
        g = await self.runner.run(argv, cwd=str(wt))
        if not g.ok:
            return res | {"status": "pr_failed", "detail": g.err[-300:], "worktree": str(wt)}
        res |= {"status": "pr_opened", "pr": g.out.strip().splitlines()[-1] if g.out.strip() else ""}
        if cfg.cleanup_worktree:
            await self._git(["worktree", "remove", "--force", str(wt)], self.repo)
        return res

    # ---- (2) RSI loop --------------------------------------------------------------------------
    def _applied_path(self) -> Path:
        return self.root / "applied.jsonl"

    def _applied(self) -> list[dict]:
        p = self._applied_path()
        return [json.loads(x) for x in p.read_text().splitlines() if x.strip()] if p.is_file() else []

    def _current(self, key: str):
        cur: Any = self.s
        for part in key.split("."):
            cur = cur.get(part) if isinstance(cur, dict) else getattr(cur, part)
        return cur

    def _apply(self, p: an.Proposal, n_events: int) -> dict | None:
        ch = p.change or {}
        overlay_p = self.root / "overlay.json"
        ov = json.loads(overlay_p.read_text()) if overlay_p.is_file() else {"config": {}, "profile_patterns": []}
        if ch.get("op") == "add_profile_pattern":
            before, after = len(ov["profile_patterns"]), None
            if ch["label"] in ov["profile_patterns"]:
                return None
            ov["profile_patterns"].append(ch["label"])
            after = len(ov["profile_patterns"])
        elif ch.get("op") == "set_config":
            key = ch["key"]
            if key in ov["config"]:
                return None
            before = self._current(key)
            after = max(32, int(before * ch["scale"]))
            ov["config"][key] = after
        else:
            return None
        self.root.mkdir(parents=True, exist_ok=True)
        overlay_p.write_text(json.dumps(ov, indent=1, sort_keys=True))
        rec = {"id": p.id, "ts": time.time(), "change": ch, "before": before, "after": after,
               "metrics_before": {"count": p.count, "window_days": self.cfg.window_days},
               "revert": "delete this id's key from overlay.json"}
        with self._applied_path().open("a") as f:
            f.write(json.dumps(rec) + "\n")
        return rec

    async def improvement_report(self, limit: int = 10, apply: bool = True) -> dict[str, Any]:
        events = an.read_events(self.data, self.cfg.window_days)
        props = an.analyze(events, min_count=self.cfg.min_cluster_count)
        changed = an.update_playbooks(props, self.playbooks)
        applied_now = []
        if apply and self.cfg.auto_apply_low_risk:
            for p in props:
                if p.tier == 1 and p.change and (rec := self._apply(p, len(events))):
                    applied_now.append(rec["id"])
        outcomes = []
        for rec in self._applied():
            after = {p.id: p.count for p in an.analyze(
                [e for e in events if float(e.get("ts", 0)) >= rec["ts"]], min_count=1)}
            outcomes.append({"id": rec["id"], "before_n": rec["metrics_before"]["count"],
                             "after_n": after.get(rec["id"], 0), "days": round((time.time() - rec["ts"]) / 86400, 1)})
        rows = [p.compact() | ({"suggest": scrub(p.suggest, 300)} if p.suggest else {}) for p in props[:limit]]
        return {"proposals": rows,
                "total": len(props), "auto_applied": applied_now, "applied_outcomes": outcomes[-5:],
                "playbooks_updated": changed, "events": len(events)}

    def playbook_hints(self, platform: str, max_chars: int = 1200) -> list[str]:
        return self.playbooks.lessons(platform, max_chars=max_chars)
