"""``job-apply-mcp init``: create config.toml, profile.toml and controls.toml from the fictional examples.

Interactive by default, fully scriptable with ``--yes`` plus flags. Existing files are never overwritten
without ``--force`` (and are then backed up to ``<name>.bak``). dry_run is always written as true.
"""
from __future__ import annotations

import json
import re
import shutil
import sys
import tomllib
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path

import httpx

from . import paths
from .sysinfo import find_system_chrome, total_ram_gb

GIT_URL = "git+https://github.com/tanmayagrawal21/job-apply-mcp"

# (name, base_url, models endpoint). Probed with a short timeout; failures are silent.
OPENAI_COMPAT_PROBES = [("LM Studio", "http://127.0.0.1:1234/v1"), ("mlx_lm.server / llama.cpp", "http://127.0.0.1:8080/v1"),
                        ("vLLM / other", "http://127.0.0.1:8000/v1")]
OLLAMA_URL = "http://127.0.0.1:11434"


def examples_dir() -> Path:
    """Packaged copy (wheel) first, then the repo checkout's examples/ (editable/source installs)."""
    here = Path(__file__).resolve().parent
    for cand in (here / "_examples", here.parents[1] / "examples"):
        if (cand / "profile.example.toml").is_file():
            return cand
    raise FileNotFoundError("example files not found; reinstall job-apply-mcp")


@dataclass
class Runtime:
    kind: str                 # ollama | openai_compat
    label: str
    base_url: str
    models: list[str] = field(default_factory=list)


def detect_runtimes(timeout: float = 0.6) -> list[Runtime]:
    found: list[Runtime] = []
    try:
        r = httpx.get(f"{OLLAMA_URL}/api/tags", timeout=timeout)
        r.raise_for_status()
        found.append(Runtime("ollama", "Ollama", OLLAMA_URL, [m["name"] for m in r.json().get("models", [])]))
    except Exception:  # noqa: BLE001, S110 - absence of a runtime is the normal case
        pass
    for label, url in OPENAI_COMPAT_PROBES:
        try:
            r = httpx.get(f"{url}/models", timeout=timeout)
            r.raise_for_status()
            found.append(Runtime("openai_compat", label, url, [m["id"] for m in r.json().get("data", [])]))
        except Exception:  # noqa: BLE001, S110
            pass
    return found


@dataclass
class TierPlan:
    small: str | None          # ollama model tag, or None to use the calling agent ("client")
    narrative: str | None
    note: str


def tier_defaults(ram_gb: float | None) -> TierPlan:
    """Sane local-model sizes for the machine's RAM. Models are suggestions; `ollama pull` is never run."""
    if ram_gb is None:
        return TierPlan("qwen3:4b", None, "RAM unknown: small model local, prose handled by your MCP client")
    if ram_gb < 8:
        return TierPlan("qwen3:1.7b", None, f"{ram_gb:g} GB RAM: tiny local model, prose by your MCP client")
    if ram_gb < 16:
        return TierPlan("qwen3:4b", "qwen2.5:7b", f"{ram_gb:g} GB RAM: 4B for fields, 7B for prose")
    return TierPlan("qwen3:4b", "gemma4:12b-it-qat", f"{ram_gb:g} GB RAM: 4B for fields, 12B for prose")


def _q(s: str) -> str:
    return json.dumps(s, ensure_ascii=True)   # JSON strings are valid TOML basic strings


def render_config(*, small: str | None, narrative: str | None, ollama: bool, openai_base: str | None,
                  openai_model: str | None, data_dir: str | None, profile: Path, controls: Path,
                  autonomy: str = "strict") -> str:
    lines = ["# Generated by `job-apply-mcp init`. Every omitted key keeps its built-in default.",
             "# Full reference: docs/configuration.md.  Override any key with JOB_APPLY__SECTION__KEY=value.",
             "", "dry_run = true   # nothing is submitted until you set this to false", ""]
    lines += ["[paths]"]
    if data_dir:
        lines.append(f"data_dir = {_q(data_dir)}")
    lines += [f"profile = {_q(str(profile))}", "", "[control]", f"rules_file = {_q(str(controls))}", ""]
    lines += ["[apply]",
              "# Caps on LIVE submissions (these are the defaults). 0 = NO LIMIT and removes that safety cap;",
              "# raising a cap or using 0 only works in this file, not from env vars or a project config (ADR-0035).",
              "# daily_limit = 25               # per rolling 24h, all platforms",
              "# daily_limit_per_platform = 10  # per rolling 24h, each platform",
              "# run_limit = 10                 # per server run", ""]
    if autonomy not in AUTONOMY_CHOICES:
        raise ValueError(f"autonomy must be one of {AUTONOMY_CHOICES}")
    lines += ["[answers]",
              "# What the agent may assume when you are not available (ADR-0052). Only this file can loosen it.",
              "#   strict       every unresolved field waits for you (default)",
              "#   safe_default decline contact/marketing permission, default 'how did you hear', decline EEO",
              "#   infer        safe_default + capability Yes/No questions answered conservatively from your resume",
              "# Never assumed at any level: authorization/visa, background checks, attestations, legal agreements,",
              "# salary without a policy, start date and location facts.",
              f"autonomy = {_q(autonomy)}",
              "# promote_after = 3   # after this many assumptions of one question, you are asked once", ""]

    def tier(section: str, provider: str, model: str, extra: str = "") -> list[str]:
        return [f"[{section}]", f"provider = {_q(provider)}", f"model = {_q(model)}", *( [extra] if extra else [])]

    if openai_base and openai_model and not ollama:
        lines += ["[llm.providers.openai_compat]", f"base_url = {_q(openai_base)}", ""]
        lines += tier("llm.tiers.small", "openai_compat", openai_model, "max_tokens = 256") + [""]
        lines += tier("llm.tiers.medium", "openai_compat", openai_model, "max_tokens = 1024") + [""]
        lines += tier("llm.task_tiers.narrative", "openai_compat", openai_model, "max_tokens = 1200") + [""]
    elif ollama and small:
        lines += tier("llm.tiers.small", "ollama", small, "max_tokens = 256\nnum_ctx = 4096") + [""]
        lines += tier("llm.tiers.medium", "ollama", small, "max_tokens = 1024\nnum_ctx = 4096\nthink = true") + [""]
        if narrative:
            lines += tier("llm.task_tiers.narrative", "ollama", narrative,
                          "max_tokens = 1200\ntemperature = 0.6\nheavy = true\nnum_ctx = 8192\ntimeout_s = 150") + [""]
        else:
            lines += tier("llm.task_tiers.narrative", "client", "client-default", "max_tokens = 1200") + [""]
    else:   # no local runtime: everything hard is handed to the calling agent; nothing local is assumed
        lines += ["# No local LLM runtime was detected. Install Ollama (https://ollama.com), pull a model, and",
                  "# re-run `job-apply-mcp init --force`, or keep this: the calling agent answers instead.",
                  "[llm]", "allow_cloud = true", ""]
        for name in ("small", "medium"):
            lines += tier(f"llm.tiers.{name}", "client", "client-default", "max_tokens = 512") + [""]
        lines += tier("llm.task_tiers.narrative", "client", "client-default", "max_tokens = 1200") + [""]
    text = "\n".join(lines).rstrip() + "\n"
    tomllib.loads(text)   # fail loudly here, never write a config the loader would reject
    return text


AUTONOMY_CHOICES = ("strict", "safe_default", "infer")
AUTONOMY_HELP = ("When you are not available, how much may the agent assume?\n"
                 "  strict       = ask me about every unresolved field (safest, default)\n"
                 "  safe_default = take only safe answers: decline contact/marketing opt-ins, default 'how did you\n"
                 "                 hear', 'decline to self-identify'\n"
                 "  infer        = safe_default + answer ordinary skill Yes/No questions from my resume, conservatively\n"
                 "  (authorization, background checks, attestations, legal agreements, salary and start date are\n"
                 "  never assumed)")

CONTACT_KEYS = ("first_name", "last_name", "email", "phone", "city", "region", "country", "postal_code")


def render_profile(example: str, contact: dict[str, str]) -> str:
    """Replace values inside the [contact] table of the example; everything else stays fictional placeholder."""
    out, in_contact = [], False
    for line in example.splitlines():
        m = re.match(r"\s*\[([^\]]+)\]\s*$", line)
        if m:
            in_contact = m.group(1).strip() == "contact"
        km = re.match(r"(\s*)(\w+)(\s*=\s*)", line)
        if in_contact and km and km.group(2) in contact and contact[km.group(2)]:
            line = f"{km.group(1)}{km.group(2)}{km.group(3)}{_q(contact[km.group(2)])}"
        out.append(line)
    text = "\n".join(out) + "\n"
    tomllib.loads(text)
    return text


def client_snippet(command_style: str = "auto") -> dict:
    """The generic stdio entry. `auto` prefers an installed console script, then uvx from the git URL."""
    exe = shutil.which("job-apply-mcp")
    if command_style == "uvx" or (command_style == "auto" and not exe):
        if shutil.which("uvx") or command_style == "uvx":
            return {"command": "uvx", "args": ["--from", GIT_URL, "job-apply-mcp"]}
        return {"command": sys.executable, "args": ["-m", "job_apply_mcp"]}
    if command_style == "python":
        return {"command": sys.executable, "args": ["-m", "job_apply_mcp"]}
    return {"command": exe or "job-apply-mcp"}


Ask = Callable[[str, str], str]


def _default_ask(prompt: str, default: str) -> str:
    suffix = f" [{default}]" if default else ""
    try:
        got = input(f"{prompt}{suffix}: ").strip()
    except EOFError:
        got = ""
    return got or default


def _write(path: Path, text: str, force: bool, log: list[str]) -> bool:
    if path.exists() and not force:
        log.append(f"kept existing {path} (use --force to overwrite; the old file is saved as .bak)")
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        shutil.copy2(path, path.with_name(path.name + ".bak"))
    path.write_text(text, encoding="utf-8")
    log.append(f"wrote {path}")
    return True


def run_init(*, yes: bool = False, force: bool = False, config_dir: Path | None = None,
             contact: dict[str, str] | None = None, model: str | None = None, ask: Ask | None = None,
             detect: Callable[[], list[Runtime]] | None = None, ram_gb: float | None = -1,
             command_style: str = "auto", out: Callable[[str], None] = print, autonomy: str | None = None) -> int:
    ask = ask or _default_ask
    cdir = config_dir or paths.config_dir()
    interactive = not yes
    log: list[str] = []
    ram = total_ram_gb() if ram_gb == -1 else ram_gb
    runtimes = (detect or detect_runtimes)()
    plan = tier_defaults(ram)
    out(f"job-apply-mcp init  (config dir: {cdir})")
    out(f"machine: {'unknown RAM' if ram is None else f'{ram:g} GB RAM'}; {plan.note}")

    ollama = next((r for r in runtimes if r.kind == "ollama"), None)
    compat = next((r for r in runtimes if r.kind == "openai_compat" and r.models), None)
    for r in runtimes:
        out(f"detected {r.label} at {r.base_url} ({len(r.models)} model(s))")
    if not runtimes:
        out("no local LLM runtime detected (Ollama :11434, LM Studio :1234, mlx/llama.cpp :8080)")

    small, narrative = model or plan.small, plan.narrative
    if ollama and model is None:
        # Prefer a model that is already pulled so the first run works without downloads.
        have = set(ollama.models)
        if small not in have:
            for cand in ("qwen3:4b", "qwen3:8b", "qwen2.5:7b", "llama3.2:3b", "gemma3:4b"):
                if cand in have:
                    small = cand
                    break
        if narrative and narrative not in have and small in have and ram is not None and ram < 16:
            narrative = None
    if interactive and ollama:
        small = ask("Ollama model for form fields", small or "") or small
    missing = [m for m in {small, narrative} if m and ollama and m not in ollama.models]

    contact = dict(contact or {})
    if interactive:
        out("\nProfile (stored only on this machine; press Enter to keep the example placeholder)")
        for k in CONTACT_KEYS[:5]:
            contact.setdefault(k, ask(f"  {k.replace('_', ' ')}", ""))

    level = autonomy or "strict"
    if interactive and autonomy is None:
        out("\n" + AUTONOMY_HELP)
        while True:
            level = (ask("  autonomy level (strict / safe_default / infer)", "strict") or "strict").strip().lower()
            if level in AUTONOMY_CHOICES:
                break
            out(f"  please answer one of {', '.join(AUTONOMY_CHOICES)}")
    if level not in AUTONOMY_CHOICES:
        out(f"unknown autonomy level {level!r}; using strict")
        level = "strict"

    ex = examples_dir()
    profile_text = render_profile((ex / "profile.example.toml").read_text(encoding="utf-8"), contact)
    controls_text = (ex / "controls.example.toml").read_text(encoding="utf-8")
    cfg_text = render_config(
        small=small, narrative=narrative, ollama=bool(ollama), openai_base=compat.base_url if compat else None,
        openai_model=compat.models[0] if compat else None, data_dir=None,
        profile=cdir / "profile.toml", controls=cdir / "controls.toml", autonomy=level)

    out("")
    _write(cdir / "config.toml", cfg_text, force, log)
    _write(cdir / "profile.toml", profile_text, force, log)
    _write(cdir / "controls.toml", controls_text, force, log)
    for line in log:
        out(line)

    out("\ndry_run = true: nothing will be submitted until you change it in config.toml.")
    out(f"answers.autonomy = {level} (change it in config.toml; a project file or env var can only make it stricter).")
    if missing:
        out("Models not pulled yet (optional, run once):")
        for m in missing:
            out(f"  ollama pull {m}")
    if not ollama and not compat:
        out("No local model: hard fields are handed to your MCP client. For local LLMs install Ollama "
            "(https://ollama.com) and re-run `job-apply-mcp init --force`.")
    if find_system_chrome() is None:
        out("Browser: no system Chrome found. For browser-based applying: pip install 'job-apply-mcp[browser]' "
            "&& playwright install chromium")
    snippet = {"mcpServers": {"job-apply": client_snippet(command_style)}}
    out("\nAdd this to your MCP client (per-client files: docs/clients/):")
    out(json.dumps(snippet, indent=2))
    out("\nNext: edit " + str(cdir / "profile.toml") + " with your real details, then run `job-apply-mcp doctor`.")
    return 0
