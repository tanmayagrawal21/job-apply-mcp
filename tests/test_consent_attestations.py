async def test_adversarial_labels_never_ticked_inside_a_window(tmp_path, clock):
    from job_apply_mcp.policy.gates import stop_phrase_hit
    s = esettings(tmp_path)
    window(s)
    # labels with an AI-use stop phrase never reach the mapper (the gate stops the posting); the rest must reach it
    # and stay unresolved
    labels = [x for x in NEVER if not stop_phrase_hit(x, s.policy.stop_phrases)]
    form = ApplicationForm(ref=POSTING.ref, submit_via=["api"], fields=[
        F("first_name", "First Name"), *[F(f"n{i}", lab, FieldKind.boolean) for i, lab in enumerate(labels)]])
    e, ad, _ = eng(tmp_path, s, form)
    out = await e.plan(POSTING.ref)
    assert out.plan.gate.decision.value == "submit" and len(labels) > 20
    assert not attest.auto_keys(out.plan.answers) and "auto_attest" not in out.plan.audit
    assert {f"n{i}" for i in range(len(labels))} <= set(out.plan.unresolved)
    r = await e.submit(POSTING.ref, {}, out.approval_id, dry_run=False)
    assert r.status == "needs_human" and ad.submits == []


