# --------------------------------------------------------------------------------------------- engine
class Clock:
    def __init__(self):
        self.t = 3_000_000.0

    def __call__(self):
        return self.t


@pytest.fixture
def clock(monkeypatch):
    c = Clock()
    monkeypatch.setattr(consent, "store_for", lambda s, run_id=None: ConsentStore(
        state_path(s), b"k" * 32, clock=c, user="fictional-owner", run_id=run_id,
        hwm_file=Path(s.paths.data_dir) / "hwm.json"))
    return c


ATTEST = "I certify that the information provided is true, accurate and complete."
AI = "I certify the information is accurate and that I wrote this without AI assistance"
FORM = ApplicationForm(ref=POSTING.ref, submit_via=["api"], fields=[
    F("first_name", "First Name"), F("email", "Email"),
    F("q_acc", ATTEST, FieldKind.boolean),
    F("q_bg", "I consent to a background check.", FieldKind.select, options=["Yes", "No"]),
    F("q_arb", "I agree to the mandatory arbitration agreement.", FieldKind.boolean),
    F("q_opt", "I acknowledge that employment with Acme Robotics is at-will.", FieldKind.boolean, required=False),
])


def esettings(tmp_path, classes=ALL, trusted=True, mode="agent"):
    s = settings()
    s.apply.approval_mode = mode
    s.paths.data_dir = str(tmp_path / "data")
    s.grants.use_keyring = False
    s.consent.auto_attest = list(classes)
    s._auto_attest_trusted = trusted
    return s


def eng(tmp_path, s, form=FORM):
    ad = FakeAdapter(form=form)
    book = ApprovalBook(tmp_path / "book")
    return ApplyEngine(s, resolve_adapter=lambda r: ad, profile=FakeProfile(), router=None, gates=FakeGates(),
                       store=FakeStore(), approvals=book), ad, book


def window(s, scopes=("approve_submissions",), secs=600):
    return consent.store_for(s).issue_consent(secs, scopes=list(scopes))


def _evidence(tmp_path) -> dict:
    p = next((tmp_path / "data" / "evidence").glob("*/attested.json"))
    return json.loads(p.read_text())


async def test_window_ticks_required_attestations_and_logs_each(tmp_path, clock):
    s = esettings(tmp_path)
    c = window(s)
    e, _, _ = eng(tmp_path, s)
    out = await e.plan(POSTING.ref)
    ans = {a.key: a for a in out.plan.answers}
    assert ans["q_acc"].value is True and ans["q_bg"].value == "Yes" and ans["q_arb"].value is True
    assert ans["q_acc"].source == "consent:auto_attest:accuracy"
    assert "q_opt" not in ans                                   # optional: never ticked
    assert not {"q_acc", "q_bg", "q_arb"} & set(out.plan.unresolved)
    rows = {r["key"]: r for r in out.plan.audit["auto_attest"]}
    assert rows["q_acc"] == {"key": "q_acc", "class": "accuracy", "label": ATTEST, "value": True,
                             "ref": POSTING.ref, "consent_id": c.id}
    assert rows["q_bg"]["class"] == "background_check" and rows["q_arb"]["class"] == "arbitration_terms"
    ev = _evidence(tmp_path)["events"]
    assert ev[0]["stage"] == "plan" and {r["key"] for r in ev[0]["auto_attested"]} == {"q_acc", "q_bg", "q_arb"}


async def test_submit_inside_window_logs_consent_id_in_audit_and_evidence(tmp_path, clock):
    s = esettings(tmp_path)
    c = window(s)
    e, ad, book = eng(tmp_path, s)
    out = await e.plan(POSTING.ref)
    r = await e.submit(POSTING.ref, {}, out.approval_id, dry_run=False)
    assert r.status == "submitted", r.detail
    assert ad.submits[0][0]["q_acc"] is True
    att = [x for x in book.audit_rows(POSTING.ref) if x["event"] == "auto_attest"]
    assert len(att) == 3 and all(x["actor"] == f"consent:{c.id}" for x in att)
    assert any(ATTEST in x["detail"] for x in att)
    assert [x["stage"] for x in _evidence(tmp_path)["events"]] == ["plan", "submit"]


