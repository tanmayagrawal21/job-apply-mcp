# --------------------------------------------------------------------------------------------- run report
class AttestAdapter(MultiAdapter):
    async def get_form(self, ref):
        f = await super().get_form(ref)
        return f.model_copy(update={"fields": [*f.fields, F("q_acc", ATTEST, FieldKind.boolean)]})


async def test_run_report_lists_auto_attestations_for_review(tmp_path, clock):
    link = "https://boards.greenhouse.io/northwind/jobs/7"
    r, _ad, e = make(tmp_path, adapter=AttestAdapter())
    e.s.grants.use_keyring = False
    e.s.consent.auto_attest = list(ALL)
    e.s._auto_attest_trusted = True
    c = window(e.s)
    rep = await r.run(links=[link], sources=["links"])
    assert rep["counts"] == {"dry_run_ok": 1}, rep
    row = rep["auto_attested"][link][0]
    assert row == {"key": "q_acc", "class": "accuracy", "label": ATTEST, "value": True,
                   "ref": link, "consent_id": c.id}
    again = await r.report()
    assert again["auto_attested"][link][0]["consent_id"] == c.id


