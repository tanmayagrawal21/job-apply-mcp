@pytest.mark.parametrize("case", ["no_window", "expired", "wrong_scope", "untrusted", "class_off", "revoked"])
async def test_no_valid_window_or_opt_in_means_no_tick(tmp_path, clock, case):
    s = esettings(tmp_path, trusted=case != "untrusted",
                  classes=["policy_ack"] if case == "class_off" else ALL)
    if case == "expired":
        window(s, secs=60)
        clock.t += 61
    elif case == "wrong_scope":
        window(s, scopes=("otp_unattended", "captcha_attempt", "credentials"))
    elif case == "revoked":
        consent.store_for(s).revoke(window(s).id)
    elif case != "no_window":
        window(s)
    e, ad, _ = eng(tmp_path, s)
    out = await e.plan(POSTING.ref)
    assert {"q_acc", "q_bg", "q_arb"} <= set(out.plan.unresolved)
    assert not attest.auto_keys(out.plan.answers) and "auto_attest" not in out.plan.audit
    r = await e.submit(POSTING.ref, {}, out.approval_id, dry_run=False)
    assert r.status == "needs_human" and ad.submits == []


